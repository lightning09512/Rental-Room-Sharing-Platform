CREATE OR REPLACE FUNCTION listings_sync_metadata() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.category_id IS NULL THEN
    SELECT id INTO NEW.category_id FROM categories WHERE type='Loại phòng' AND name=NEW.room_type LIMIT 1;
  END IF;
  IF NEW.location_id IS NULL THEN
    SELECT id INTO NEW.location_id FROM locations
    WHERE unaccent(NEW.location) ILIKE '%' || unaccent(name) || '%'
    ORDER BY length(name) DESC LIMIT 1;
  END IF;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS listings_metadata_trigger ON listings;
CREATE TRIGGER listings_metadata_trigger
BEFORE INSERT OR UPDATE OF room_type,location ON listings
FOR EACH ROW EXECUTE FUNCTION listings_sync_metadata();

CREATE OR REPLACE FUNCTION listings_sync_normalized_data() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM listing_images WHERE listing_id=NEW.id;
  IF NEW.image_url<>'' THEN
    INSERT INTO listing_images(listing_id,image_url,is_cover,display_order) VALUES(NEW.id,NEW.image_url,true,0);
  END IF;
  INSERT INTO listing_images(listing_id,image_url,is_cover,display_order)
  SELECT NEW.id,item.url,false,item.ord::integer
  FROM jsonb_array_elements_text(NEW.gallery) WITH ORDINALITY item(url,ord)
  WHERE item.url<>'' AND item.url<>NEW.image_url;

  INSERT INTO amenities(name)
  SELECT DISTINCT value FROM jsonb_array_elements_text(NEW.amenities)
  ON CONFLICT(name) DO NOTHING;
  DELETE FROM listing_amenities WHERE listing_id=NEW.id;
  INSERT INTO listing_amenities(listing_id,amenity_id)
  SELECT NEW.id,a.id FROM jsonb_array_elements_text(NEW.amenities) item(name)
  JOIN amenities a ON a.name=item.name
  ON CONFLICT DO NOTHING;

  RETURN NULL;
END; $$;
DROP TRIGGER IF EXISTS listings_normalized_data_trigger ON listings;
CREATE TRIGGER listings_normalized_data_trigger
AFTER INSERT OR UPDATE OF image_url,gallery,amenities ON listings
FOR EACH ROW EXECUTE FUNCTION listings_sync_normalized_data();
