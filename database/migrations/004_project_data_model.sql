UPDATE listings l SET category_id=(
  SELECT id FROM categories c WHERE c.type='Loại phòng' AND c.name=l.room_type LIMIT 1
) WHERE category_id IS NULL;

CREATE TABLE IF NOT EXISTS listing_images (
  id text PRIMARY KEY DEFAULT gen_random_uuid()::text,
  listing_id text NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  image_url text NOT NULL,
  is_cover boolean NOT NULL DEFAULT false,
  display_order integer NOT NULL DEFAULT 0 CHECK (display_order >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS listing_images_listing_idx ON listing_images(listing_id, display_order);
CREATE UNIQUE INDEX IF NOT EXISTS listing_images_one_cover_idx ON listing_images(listing_id) WHERE is_cover;

CREATE TABLE IF NOT EXISTS listing_amenities (
  listing_id text NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  amenity_id bigint NOT NULL REFERENCES amenities(id) ON DELETE RESTRICT,
  PRIMARY KEY(listing_id, amenity_id)
);

CREATE TABLE IF NOT EXISTS forum_posts (
  id text PRIMARY KEY DEFAULT gen_random_uuid()::text,
  author_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title text NOT NULL DEFAULT '',
  content text NOT NULL CHECK (length(trim(content)) BETWEEN 2 AND 5000),
  image_url text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('pending','active','hidden','rejected')),
  moderation_note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS forum_posts_status_created_idx ON forum_posts(status, created_at DESC);
CREATE INDEX IF NOT EXISTS forum_posts_author_created_idx ON forum_posts(author_id, created_at DESC);

CREATE TABLE IF NOT EXISTS forum_comments (
  id text PRIMARY KEY DEFAULT gen_random_uuid()::text,
  post_id text NOT NULL REFERENCES forum_posts(id) ON DELETE CASCADE,
  author_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  content text NOT NULL CHECK (length(trim(content)) BETWEEN 1 AND 3000),
  is_hidden boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS forum_comments_post_created_idx ON forum_comments(post_id, created_at);

CREATE TABLE IF NOT EXISTS forum_reactions (
  post_id text NOT NULL REFERENCES forum_posts(id) ON DELETE CASCADE,
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  reaction_type text NOT NULL DEFAULT 'like' CHECK (reaction_type IN ('like')),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(post_id, user_id)
);

CREATE TABLE IF NOT EXISTS property_interactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id text NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
  user_id text REFERENCES users(id) ON DELETE SET NULL,
  interaction_type text NOT NULL CHECK (interaction_type IN ('view','contact')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS property_interactions_listing_type_idx ON property_interactions(listing_id, interaction_type, created_at DESC);
CREATE INDEX IF NOT EXISTS property_interactions_user_idx ON property_interactions(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS system_warnings (
  id text PRIMARY KEY DEFAULT gen_random_uuid()::text,
  recipient_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  actor_id text REFERENCES users(id) ON DELETE SET NULL,
  report_id text REFERENCES reports(id) ON DELETE SET NULL,
  content text NOT NULL CHECK (length(trim(content)) BETWEEN 1 AND 3000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS system_warnings_recipient_idx ON system_warnings(recipient_id, created_at DESC);

-- PostgreSQL outbox preserves decisions made in SQL transactions while MongoDB
-- remains the storage required by the report for user notifications.
CREATE TABLE IF NOT EXISTS notification_outbox (
  id text PRIMARY KEY DEFAULT gen_random_uuid()::text,
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title text NOT NULL,
  detail text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  delivered_at timestamptz
);
CREATE INDEX IF NOT EXISTS notification_outbox_pending_idx ON notification_outbox(created_at) WHERE delivered_at IS NULL;

